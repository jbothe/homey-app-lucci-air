'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const protocol = require('../lib/lucci-protocol');
const cr2032 = require('../lib/cr2032-protocol');
const { FAN_SPEEDS, FAN_DIRECTIONS, FAN_TIMERS } = protocol;

const root = path.join(__dirname, '..');
const read = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const app = read('app.json');
const composeApp = read('.homeycompose/app.json');
const signal = read('.homeycompose/signals/433/lucci.json');
const signalCr2032 = read('.homeycompose/signals/433/lucci_cr2032.json');
const driver = read('drivers/fan/driver.compose.json');
const drivers = ['fan', 'light', 'fan-cr2032', 'light-cr2032']
    .map(id => read(`drivers/${id}/driver.compose.json`));
const capability = id => read(`.homeycompose/capabilities/${id}.json`);

// app.json is generated by `homey app build` and committed. These catch it
// drifting from the .homeycompose sources it was generated from.
test('app.json is in step with .homeycompose', async (t) => {
    await t.test('app metadata', () => {
        assert.equal(app.id, composeApp.id);
        assert.equal(app.id, 'com.lucci.fan');
        assert.equal(app.version, composeApp.version);
        assert.deepEqual(app.permissions, ['homey:wireless:433']);
    });

    await t.test('signal', () => {
        assert.deepEqual(app.signals[433][protocol.SIGNAL_ID], signal);
        assert.deepEqual(app.signals[433][cr2032.SIGNAL_ID], signalCr2032);
    });

    await t.test('drivers', () => {
        for (const compose of drivers) {
            const built = app.drivers.find(d => d.id === compose.id);
            assert.ok(built, `the ${compose.id} driver is present`);
            assert.deepEqual(built.capabilities, compose.capabilities);
            assert.equal(built.class, compose.class);
        }
        assert.equal(app.drivers.length, 4);
    });

    await t.test('capabilities', () => {
        for (const id of Object.keys(app.capabilities)) {
            assert.deepEqual(app.capabilities[id], capability(id), id);
        }
        assert.deepEqual(Object.keys(app.capabilities).sort(), [
            'lucci_brighter', 'lucci_dimmer', 'lucci_direction', 'lucci_resync',
            'lucci_reverse', 'lucci_speed', 'lucci_timer', 'lucci_toggle',
        ]);
    });
});

test('the version in package.json matches the app manifest', () => {
    assert.equal(read('package.json').version, app.version);
});

test('every picker value has a code behind it', () => {
    // A capability offering a value the command table has no code for would look
    // like a working control and do nothing. The table is the source: these read
    // the ids out of the manifest and hold them against it.
    const ids = id => capability(id).values.map(v => v.id);

    assert.deepEqual(ids('lucci_speed'), FAN_SPEEDS);
    assert.deepEqual(ids('lucci_direction'), FAN_DIRECTIONS);
    assert.deepEqual(ids('lucci_timer'), FAN_TIMERS);

    // And every value is labelled in every language the app ships.
    for (const id of ['lucci_speed', 'lucci_direction', 'lucci_timer']) {
        for (const value of capability(id).values) {
            for (const lang of ['en', 'nl', 'de', 'fr']) {
                assert.ok(value.title[lang], `${id}.${value.id} has no ${lang} title`);
            }
        }
    }
});

test('the enums are pickers, and stay out of Insights', () => {
    for (const id of ['lucci_speed', 'lucci_direction', 'lucci_timer']) {
        const custom = capability(id);
        assert.equal(custom.type, 'enum', id);
        assert.equal(custom.uiComponent, 'picker', id);
        assert.equal(custom.getable, true, id);
        assert.equal(custom.setable, true, id);
    }

    // An enum logged to Insights produces a chart of category labels, which says
    // nothing. Set per driver rather than on the capability, which is where
    // Homey reads it.
    for (const id of driver.capabilities.filter(c => c.startsWith('lucci_'))) {
        assert.equal(driver.capabilitiesOptions[id].preventInsights, true, id);
    }
});

test('the light offers what a relative protocol allows, and no more', () => {
    const compose = drivers.find(d => d.id === 'light');

    // `dim` is here despite brightness being relative, because the light
    // saturates at both ends — so a slider can be made exact by driving into an
    // end stop. The two buttons are the honest core: one tap, one step, correct
    // however the light got to where it is.
    assert.deepEqual(compose.capabilities,
        ['onoff', 'dim', 'lucci_brighter', 'lucci_dimmer', 'lucci_toggle', 'lucci_resync']);
    assert.equal(compose.class, 'light');
    assert.equal(compose.rf433.satelliteMode, true);

    // The one thing a user can do to repair an estimate that has drifted.
    assert.deepEqual((compose.repair || []).map(v => v.id), ['calibrate']);

    // A slider logged to Insights would chart an estimate as though it were a
    // measurement.
    assert.equal(compose.capabilitiesOptions.dim.preventInsights, true);
});

test('the brightness buttons are buttons, not switches', () => {
    // A tap, not a state: there is nothing to read back, so a getable boolean
    // would show a checkbox that means nothing.
    for (const id of ['lucci_brighter', 'lucci_dimmer', 'lucci_toggle', 'lucci_resync']) {
        const custom = capability(id);
        assert.equal(custom.type, 'boolean', id);
        assert.equal(custom.uiComponent, 'button', id);
        assert.equal(custom.getable, false, id);
        assert.equal(custom.setable, true, id);
    }
});

test('the fan offers every control the protocol can command absolutely', () => {
    // All four, now that the fan has answered: power and speed are confirmed on
    // the hardware, direction and the timer are wired but have never been sent.
    // The light is a separate device and a separate driver — its brightness is
    // relative, so it cannot be a capability of this shape at all.
    assert.deepEqual(driver.capabilities, ['onoff', 'lucci_speed', 'lucci_direction', 'lucci_timer']);
    assert.deepEqual(driver.connectivity, ['rf433']);
    assert.equal(driver.class, 'fan');

    // Without satelliteMode Homey routes no received frame to the driver at all,
    // while enableRX() still resolves successfully. Pairing listens, so this is
    // load-bearing already. See RF_PROTOCOL.md.
    assert.equal(driver.rf433.satelliteMode, true);
});

test('the signal transmits what the handset transmits, and no more', () => {
    // Nine repetitions, matching the handset. On the sibling RC300 app,
    // transmitting materially longer than the real remote made the receiver
    // re-trigger and register one Homey command as two presses — so this is an
    // upper bound as much as a setting.
    assert.equal(signal.repetitions, 9);

    // Both omissions are what make receiving work at all: Homey will not match a
    // frame against a definition declaring an eof unless it observes that eof on
    // air, and txOnly would switch receiving off.
    assert.equal('eof' in signal, false);
    assert.equal('txOnly' in signal, false);

    // The 10ms default expires inside a 37.6ms frame.
    assert.equal(signal.rxTimeout, 255);

    // 25 bits go out. 24 is the allowance for a receiver that never closes the
    // final word, as the sibling Bear handset's does not; identifyFrame accepts
    // both because the parity bit is recomputed rather than carried over.
    assert.equal(signal.maximalLength, protocol.FRAME_LENGTH);
    assert.equal(signal.minimalLength, protocol.RX_FRAME_LENGTH);
    assert.equal(protocol.RX_FRAME_LENGTH, protocol.FRAME_LENGTH - 1);

    // A tolerance that sounds safely permissive makes the two symbols
    // undecidable: 0.5 is enough for bit 0 and bit 1 to overlap. See
    // RF_PROTOCOL.md on sensitivity.
    assert.ok(signal.sensitivity >= 0.1 && signal.sensitivity <= 0.4, 'sensitivity is in the usable run');
});

test('every custom view has a file where Homey looks for it', () => {
    // Pair views are read from drivers/<id>/pair, repair views from
    // drivers/<id>/repair — a different folder, which the build says nothing
    // about. Getting it wrong validates and packages cleanly, and fails only
    // when a user opens the view, as `unknown_error_getting_file`.
    for (const compose of drivers) {
        for (const kind of ['pair', 'repair']) {
            for (const view of compose[kind] || []) {
                // A step built from one of Homey's own templates brings its own HTML.
                if (view.template || view.$template) continue;

                const file = path.join(root, 'drivers', compose.id, kind, `${view.id}.html`);
                assert.ok(fs.existsSync(file),
                    `${kind} view '${view.id}' needs drivers/${compose.id}/${kind}/${view.id}.html`);
            }
        }
    }
});

test('a view either uses Homey\'s Continue button or moves itself on, never both', () => {
    // A step declaring `navigation` gets Homey's own nav bar and its Continue
    // button underneath whatever the view has drawn. That button is the one to
    // use — it is where people expect it and it matches every other wizard — so
    // a view that has it must not also advance itself, or there are two controls
    // on screen doing the same job.
    for (const compose of drivers) {
        for (const kind of ['pair', 'repair']) {
            for (const view of compose[kind] || []) {
                if (view.template) continue;

                const html = fs.readFileSync(
                    path.join(root, 'drivers', compose.id, kind, `${view.id}.html`), 'utf8');
                const advancesItself = /Homey\.(showView|nextView)\s*\(/.test(html);
                const where = `${compose.id} ${kind} view '${view.id}'`;

                assert.ok(!(view.navigation && advancesItself),
                    `${where} has Homey's Continue button, so it must not also move itself on`);

                // A pair view is a step on the way somewhere and needs one of
                // the two. A repair view is not: it is the whole session, and
                // finishes rather than advancing.
                if (kind === 'pair') {
                    assert.ok(view.navigation || advancesItself, `${where} offers no way forward`);
                } else {
                    assert.match(html, /Homey\.done\s*\(/, `${where} must end the session with Homey.done()`);
                }
            }
        }
    }
});

test('every string the app asks for is in every locale', () => {
    // homey.__() on a missing key renders the key itself into the UI, which
    // validates and packages cleanly. These are the keys the driver, the device
    // and the pair view actually ask for.
    const used = new Set();
    // Every view, found rather than listed: state.html was added and missed off
    // this list, so its strings went unchecked — and a missing one renders the
    // key itself into the pairing wizard.
    const views = fs.readdirSync(path.join(root, 'drivers'))
        .flatMap(driver => ['pair', 'repair'].flatMap(kind => {
            const dir = path.join(root, 'drivers', driver, kind);
            if (!fs.existsSync(dir)) return [];
            return fs.readdirSync(dir)
                .filter(file => file.endsWith('.html'))
                .map(file => `drivers/${driver}/${kind}/${file}`);
        }));
    assert.ok(views.length >= 3, `only found ${views.length} views; the walk has stopped working`);

    const sources = [
        'lib/lucci-driver.js', 'lib/cr2032-driver.js',
        'drivers/fan-cr2032/driver.js', 'drivers/fan-cr2032/device.js',
        'drivers/light-cr2032/driver.js', 'drivers/light-cr2032/device.js',
        'drivers/fan/driver.js', 'drivers/fan/device.js', 'drivers/fan/pair/learn.html',
        'drivers/light/driver.js', 'drivers/light/device.js', 'drivers/light/pair/learn.html',
        'drivers/light/pair/state.html', 'drivers/light/repair/calibrate.html',
    ];
    for (const file of [...new Set([...sources, ...views])]) {
        const source = fs.readFileSync(path.join(root, file), 'utf8');
        for (const [, key] of source.matchAll(/__\(\s*'([a-z_]+\.[a-z_]+)'\s*\)/g)) used.add(key);
    }
    // learn.html builds this one as 'pair.' + buttonKey, so no literal appears.
    used.add('pair.retry');

    // learn.html builds 'calibrate.' + key for two of its buttons, and
    // calibrate.html passes a second argument for the countdown.
    for (const key of ['calibrate.started_hint', 'calibrate.to_dimmest', 'calibrate.to_brightest']) used.add(key);

    assert.ok(used.size >= 20, `only found ${used.size} keys; the scan has probably stopped matching`);

    for (const lang of ['en', 'nl', 'de', 'fr']) {
        const strings = read(`locales/${lang}.json`);
        for (const key of used) {
            const value = key.split('.').reduce((at, part) => (at === undefined ? undefined : at[part]), strings);
            assert.equal(typeof value, 'string', `locales/${lang}.json is missing ${key}`);
        }
    }
});

test('the CR2032 remote has a signal of its own, and it is the one that was verified', () => {
    // A different protocol, not a variant: it must not share the USB-C remote's
    // signal, or each would try to decode the other's frames.
    assert.notEqual(cr2032.SIGNAL_ID, protocol.SIGNAL_ID);

    // Nine repetitions. OFF stopped the fan at 9 and did not at 1, 2 or 5, so 9
    // is the verified count and not merely the remote's.
    assert.equal(signalCr2032.repetitions, 9);
    assert.deepEqual(signalCr2032.sof, [348], 'one preamble pulse');
    // index = bit: 0 is a long gap then a short pulse, 1 the reverse.
    assert.deepEqual(signalCr2032.words, [[694, 348], [348, 694]]);

    // Same receive requirements as the other signal, for the same reasons.
    assert.equal('eof' in signalCr2032, false);
    assert.equal('txOnly' in signalCr2032, false);
    assert.equal(signalCr2032.rxTimeout, 255);
    assert.equal(signalCr2032.maximalLength, cr2032.FRAME_LENGTH);
    assert.equal(signalCr2032.minimalLength, cr2032.SHORT_FRAME_LENGTH);
    assert.ok(signalCr2032.sensitivity >= 0.1 && signalCr2032.sensitivity <= 0.3,
        'sensitivity keeps 348 and 694 apart (0.33 and up lets them overlap)');
});

test('the CR2032 fan offers what its remote can do, and no more', () => {
    const compose = drivers.find(d => d.id === 'fan-cr2032');

    // No timer: the remote has none. And no direction PICKER: its one Reverse
    // button sends the same code every press, so it can flip and cannot say which
    // way the fan turns, and the fan reports nothing. A picker would claim a
    // direction nobody knows. Power, the six absolute speeds, and a button.
    assert.deepEqual(compose.capabilities, ['onoff', 'lucci_speed', 'lucci_reverse']);
    assert.equal(compose.class, 'fan');
    assert.equal(compose.rf433.satelliteMode, true);

    // Speeds I to VI are the capability's six steps.
    assert.deepEqual(capability('lucci_speed').values.map(v => v.id), cr2032.FAN_SPEEDS);

    // A button that does one thing, named for it.
    const custom = capability('lucci_reverse');
    assert.equal(custom.uiComponent, 'button');
    assert.equal(custom.getable, false);
    assert.equal(custom.setable, true);
    assert.equal(custom.title.en, 'Change direction');
    assert.ok(!fs.existsSync(path.join(root, '.homeycompose/capabilities/lucci_resync_direction.json')),
        'nothing is left to correct, so the resync button is gone');
});

